"""Regenerate the login-only face from the existing licensed brand font.

Run manually with Python fonttools and brotli; production builds consume the
committed WOFF2 and do not need Python. Keep the visible login/filing copy here.
"""
from pathlib import Path
from fontTools import subset

root = Path(__file__).resolve().parents[2]
copy = '跳到主要内容账号密码登录中…或企业微信扫码正在加载二维码请使用扫一扫返回蜀ICP备号加载失败网络连接超时请重试授权暂不可用'
options = subset.Options()
options.flavor = 'woff2'
font = subset.load_font(str(root / 'miniprogram/fonts/SourceHanSerifCN-Regular.woff2'), options)
available = set(font.getBestCmap()).intersection(map(ord, copy))
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=available)
subsetter.subset(font)
destination = root / 'management/src/assets/SourceHanSerifCN-Login.woff2'
destination.parent.mkdir(parents=True, exist_ok=True)
subset.save_font(font, str(destination), options)
unicode_range = ', '.join(f'U+{code:X}' for code in sorted(available))
(destination.parent / 'login-font-range.ts').write_text(
    "// Generated by management/scripts/subset-login-font.py.\n"
    + "export const loginSongUnicodeRange = '" + unicode_range + "';\n",
    encoding='utf-8',
)
print(f'{destination.name}: {destination.stat().st_size} bytes')
print('unicode-range: ' + unicode_range + ';')
